/**
 * Emit the committed wasm as a base64 TS module.
 *
 * The module is inlined rather than fetched so the static export keeps working:
 * `next build` produces a plain `out/` directory, and a runtime `fetch` of a
 * sibling `.wasm` would need a served MIME type and survive a strict CSP. At a
 * couple of KB, the base64 costs less than that arrangement. The `.wasm` stays
 * committed beside it as the real artifact — a vitest case asserts the two agree,
 * so a hand-edited or half-regenerated pair fails the unit gate.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [, , wasmPath, outPath] = process.argv;
if (!wasmPath || !outPath) {
  console.error('usage: emit-binary-module.mjs <chores.wasm> <out.ts>');
  process.exit(1);
}

const bytes = readFileSync(wasmPath);
const base64 = bytes.toString('base64');
const lines = (base64.match(/.{1,96}/g) ?? []).map((chunk) => `  '${chunk}' +`);
lines[lines.length - 1] = lines[lines.length - 1].replace(/ \+$/, '');

writeFileSync(
  outPath,
  `/**
 * GENERATED by native/gpu-chores-wasm/scripts/build-wasm.sh — do not edit.
 *
 * Base64 of app/lib/gpuChores/wasm/chores.wasm, inlined so the static export
 * needs no extra fetch. Regenerate with \`npm run build:chores-wasm\`.
 */

/** Byte length of the module, asserted against the committed .wasm in tests. */
export const CHORES_WASM_BYTES = ${bytes.length};

export const CHORES_WASM_BASE64 =
${lines.join('\n')};
`,
);
