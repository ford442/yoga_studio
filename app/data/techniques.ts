export const DEFAULT_TECHNIQUE = TECHNIQUES[0];

export const getTechniqueById = (id: string): SessionMode | undefined =>
  TECHNIQUES.find((t) => t.id === id);

export const filterTechniquesByGoal = (
  techniques: SessionMode[],
  goal: import('../types/technique').PracticeGoal | 'all',
): SessionMode[] => {
  if (goal === 'all') return techniques;
  return techniques.filter((t) => t.technique.goals.includes(goal));
};

export const getRecommendedTechniques = (techniques: SessionMode[]): SessionMode[] =>
  techniques.filter((t) => t.technique.beginnerFriendly);
